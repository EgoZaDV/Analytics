def peak_search(arr):
  if len(arr) < 3: #Проверка длины массива
    print("Массив не горный")
  low = 0
  high = len(arr) - 1
  while low < high:
    mid = low + (high - low) // 2 #Середина массива
    if arr[mid] < arr[mid+1]: #Сравниваем средний элемент массива со следующим
      low = mid + 1 #Пик находится справа, сдвигаем левую границу
    else:
      high = mid #Иначе пик слева, двигаем правую границу
    
  if low == 0 or low == len(arr) - 1: #Пик не может быть первым или последним элементом
    return "Массив не горный"
    
  for i in range(low): #Проверяем строгое возрастание до пика, иначе массив не горный
    if arr[i] >= arr[i+1]:
      return "Массив не горный"
    
  for i in range(low, len(arr)-1): #Проверяем строгое убывание после пика, иначе массив не горный
    if arr[i] <= arr[i+1]:
      return "Массив не горный"

  return low #Если все верно выводим индекс пика

