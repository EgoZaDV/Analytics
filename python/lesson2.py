def bin_search(arr, x): #Функция вставки элемента в массив
  low = 0
  high = len(arr)

  while low < high:
    mid = low + (high - low) // 2
    if arr[mid] < x: #Все элементы слева и сам arr[mid] меньше x - нужно искать правее
      low = mid + 1
    else: #Иначе искомая позиция находится на mid или левее
      high = mid
  return low #В таком случае low и будет индексом вставки


