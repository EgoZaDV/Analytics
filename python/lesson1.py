from math import *

def f(n):
  return (1 - n)**0.5 - tan(n)

esp = 0.0001
a, b = 0, 1
step = 0

#Формула хорды и сравнение с предыдущим шагом
xk = a - ((f(a) * (b - a)) / (f(b) - f(a)))
xk1 = a

while abs(xk - xk1) > esp: #Как и в 1 задании, только здесь разность соседних приближений
  if f(xk1) * f(xk) < 0: #Опять же проверяем, в какой части знак минуса
    b = xk
  else:
    a = xk
  
  xk1 = xk #Обновляем предыдущих шаг и новый
  xk = a - ((f(a) * (b - a)) / (f(b) - f(a)))
  step += 1
  print(step, xk)
print(xk)
