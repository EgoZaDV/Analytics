#Задание 1
from math import *

#Функция
def f(n):
  return (1 - n)**0.5 - tan(n)

#Переменные
esp = 0.0001
L, R = 0, 1
B = 0
step = 0

while abs(R - L) > esp:  #Цикл пока расстояние между двумя крайними точками отрезка больше esp
  step += 1
  B = (L + R) / 2 #Середина отрезка
  if f(L) * f(B) < 0:  #Проверяем в какой части знак минуса, если слева - то сдвигаем правую границу
    R = B
  else: #иначе наоборот
    L = B
  print(step, B)
print(B)


